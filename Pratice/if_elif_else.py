# Ideia: alteração e verificação de senha

print("Para escolher uma senha, ela deve conter no mínimo 10 caracteres.")
senha_1 = input("Digite a nova senha: ")
senha_2 = input("Digite novamente: ")

if senha_1 == senha_2:
    print("A sua senha foi redefinida!")

elif senha_1 != senha_2:
    print("As duas senhas não coincidem, tente novamente.")


