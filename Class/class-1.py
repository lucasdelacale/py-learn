# Python3 - Aula 1

# Função print() - Imprime na tela
print("Olá, Mundo!")  # Imprime a mensagem "Olá, Mundo!" na tela

# Passando mais de um argumento para a função print()
print("Dois", "argumentos")  # Imprime a mensagem "Dois argumentos" na tela

# Utilizando a função sep para definir o separador entre os argumentos
print("Bem", "Vindo!", sep="-")  # Imprime a mensagem "Bem-Vindo!" na tela
